#!/usr/bin/env bash
# workspace-7wg — this repo's .gitignore must ignore node_modules however it is
# spelled on disk: a real directory, a symlink, or a DANGLING symlink.
#
# WHY (measured 2026-09-10). `.gitignore` carried `node_modules/` with a
# TRAILING SLASH, which git matches against DIRECTORIES ONLY. In this repo
# per-worktree node_modules are symlinks — .worktrees/review-295/api/node_modules
# pointed at .worktrees/ops-2656/api/node_modules, a worktree that had since been
# removed — so git reported `?? api/node_modules` and that worktree read DIRTY
# forever. Three costs, in order of how likely they are to bite:
#
#   1. the workspace-hygiene watcher's worktree-accumulation arm (homelab-iac
#      #923) treats not-provably-clean as a finding at ANY count, deliberately,
#      because such a worktree may hold the only copy of somebody's work. Here it
#      holds a broken symlink, so the finding recurs nightly and nothing clears
#      it. A finding that cannot be resolved is one people learn to skip.
#   2. `git add -A` in that worktree commits a symlink pointing outside the repo.
#   3. wt-remove's clean gate refuses to retire the worktree for the same reason,
#      so it cannot be tidied through the safe path either.
#
# BOTH ARMS ARE REQUIRED. Proving a symlink is now ignored says nothing about
# whether a real directory still is, and widening the pattern is exactly the edit
# that could regress the common case. This runs all six combinations.
#
# git status --porcelain -uall, never `git check-ignore`: the two disagree
# (workspace-ayt), and status is what the watcher, wt-remove and a human all read.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
PATTERN_FILE="$REPO_ROOT/.gitignore"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# Fixture repos must not inherit the operator's git config -- core.hooksPath in
# particular would run this box's hooks inside a throwaway repo.
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null

fail=0
pass=0

# Extract the repo's OWN node_modules rule rather than restating it. A
# hand-copied pattern would let this test pass against a .gitignore that no
# longer contains it.
mapfile -t RULES < <(grep -nE '^\s*!?node_modules/?\s*$' "$PATTERN_FILE" || true)
if [ "${#RULES[@]}" -eq 0 ]; then
  echo "FAIL: no node_modules rule found in $PATTERN_FILE at all"
  exit 1
fi
echo "rule(s) under test, read from $PATTERN_FILE:"
printf '  %s\n' "${RULES[@]}"
PATTERN="$(printf '%s\n' "${RULES[0]}" | cut -d: -f2- | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')"

check() {
  local kind="$1" expect="$2"
  rm -rf "$TMP/t"; mkdir -p "$TMP/t"
  (
    cd "$TMP/t"
    git init -q -b main .
    git config user.email t@example.com
    git config user.name t
    printf '%s\n' "$PATTERN" > .gitignore
    mkdir -p api
    case "$kind" in
      dir)      mkdir -p api/node_modules && touch api/node_modules/x.js ;;
      symlink)  mkdir -p real && touch real/x.js && ln -s ../real api/node_modules ;;
      dangling) ln -s ../gone-away api/node_modules ;;
      *)        echo "unknown fixture kind $kind" >&2; exit 2 ;;
    esac
    git status --porcelain -uall | grep -c node_modules || true
  ) > "$TMP/out" 2>/dev/null
  local n; n="$(tail -1 "$TMP/out")"
  local got; [ "$n" = "0" ] && got=ignored || got=untracked
  if [ "$got" = "$expect" ]; then
    printf "  ok    %-9s -> %s\n" "$kind" "$got"; pass=$((pass + 1))
  else
    printf "  FAIL  %-9s -> %s (expected %s)\n" "$kind" "$got" "$expect"; fail=$((fail + 1))
  fi
}

echo "pattern in force: '$PATTERN'"
check dir      ignored
check symlink  ignored
check dangling ignored

# A control in the other direction: the fixture must be able to report
# `untracked`, or every line above is vacuous. An unrelated file is not covered
# by any node_modules rule and must show up.
rm -rf "$TMP/c"; mkdir -p "$TMP/c"
(
  cd "$TMP/c"
  git init -q -b main .
  git config user.email t@example.com
  git config user.name t
  printf '%s\n' "$PATTERN" > .gitignore
  touch definitely-not-ignored.txt
  git status --porcelain -uall | grep -c definitely-not-ignored || true
) > "$TMP/cout" 2>/dev/null
if [ "$(tail -1 "$TMP/cout")" = "1" ]; then
  echo "  ok    control   -> an unignored file IS reported (the checks above can fail)"
  pass=$((pass + 1))
else
  echo "  FAIL  control   -> the fixture reports nothing as untracked; every check above is vacuous"
  fail=$((fail + 1))
fi

echo "$pass passed, $fail failed"
[ "$fail" -eq 0 ]
